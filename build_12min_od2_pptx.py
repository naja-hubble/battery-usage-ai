def big_fig(slide, img, max_w=8.4, max_h=4.7, left=0.5, top=1.05):
    p = FIG / img
    if not p.exists():
        return
    iw, ih = Image.open(p).size
    scale = min(Inches(max_w) / iw, Inches(max_h) / ih)
    slide.shapes.add_picture(str(p), EM(Inches(left)), EM(Inches(top)),
                             width=EM(iw * scale), height=EM(ih * scale))


def fig_slide(title, tag, img, points, tw, accent=DGREEN):
    s = D.section(title, accent, tag)
    big_fig(s, img)
    tf = dc._tb(s, Inches(9.1), Inches(1.15), Inches(3.9), Inches(5.0))
    D.bullets(tf, points, size=12.5, gap=6)
    D.takeaway(s, tw)
    D.footer(s)
    return s


